const regionNames =
  typeof Intl !== "undefined" ? new Intl.DisplayNames(["en"], { type: "region" }) : null;

type LocaleValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (text: string) => string;
};

const LocaleContext = createContext<LocaleValue | null>(null);

export function translate(lang: Lang, text: string): string {
  if (lang !== "en" || !text) return text;
  return EN[text] ?? text;
}

export function countryLabel(code: string, lang: Lang): string {
  if (lang !== "en") return COUNTRY_LABEL_ZH[code] ?? code;
  try {
    return regionNames?.of(code) ?? COUNTRY_LABEL_ZH[code] ?? code;
  } catch {
    return COUNTRY_LABEL_ZH[code] ?? code;
  }
}

export function countryLanguageLine(code: string, lang: Lang): string | undefined {
  const info = getCountryLanguage(code);
  if (!info) return undefined;
  return `${translate(lang, info.zone)} · ${translate(lang, info.languages)}`;
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => readSiteHash().lang);
  useEffect(() => {
    const apply = () => setLangState(readSiteHash().lang);
    window.addEventListener("hashchange", apply);
    window.addEventListener("popstate", apply);
    return () => {
      window.removeEventListener("hashchange", apply);
      window.removeEventListener("popstate", apply);
    };
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  }, [lang]);
  const value = useMemo<LocaleValue>(
    () => ({
      lang,
      setLang: (next) => {
        writeSiteHash({ lang: next });
        setLangState(next);
      },
      t: (text) => translate(lang, text),
    }),
    [lang],
  );
  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale(): LocaleValue {
  return useContext(LocaleContext) ?? { lang: "zh", setLang: () => {}, t: (text) => text };
}

export function useT(): (text: string) => string {
  return useLocale().t;
}
